CREATE TABLE authors (
    id UUID NOT NULL,
    name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    CONSTRAINT pk_authors PRIMARY KEY (id)
);

CREATE TABLE books (
    id UUID NOT NULL,
    title VARCHAR(50) NOT NULL,
    isbn VARCHAR(10) NOT NULL,
    category INT4 NOT NULL,
    CONSTRAINT pk_books PRIMARY KEY (id)
);

CREATE TABLE author_books (
    id UUID NOT NULL,
    author_id UUID NOT NULL,
    book_id UUID NOT NULL,
    CONSTRAINT pk_author_books PRIMARY KEY (id),
    CONSTRAINT fk_author_books_author_id FOREIGN KEY (author_id) REFERENCES authors (id),
    CONSTRAINT fk_author_books_book_id FOREIGN KEY (book_id) REFERENCES books (id),
    CONSTRAINT uk_author_books_author_id_book_id UNIQUE (author_id, book_id)
);
